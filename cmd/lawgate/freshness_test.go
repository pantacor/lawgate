package main

import (
	"testing"

	"github.com/pantacor/lawgate/inventory"
)

// TestGenerationRejectsMissingTargetEvidence enforces generated-is-fresh by
// requiring comparisons for explicitly declared targets.
func TestGenerationRejectsMissingTargetEvidence(t *testing.T) {
	t.Run("failed command with fresh evidence", checkFailedGenerationCommand)
	root := t.TempDir()
	module := fixtureModule(".", withoutMachines)
	module.GenerateCheck = []string{"sh", "-c", ":"}
	writeGoLawModule(t, root, module)
	writeConfig(t, root, []inventory.Module{module})
	directory, err := runCheck(t, root)
	if err == nil {
		t.Fatal("check accepted generate_check without target evidence")
	}
	assertReport(t, directory, "001.xml", "reported no targets")
}

func checkFailedGenerationCommand(t *testing.T) {
	root := t.TempDir()
	module := fixtureModule(".", withoutMachines)
	module.GenerateCheck = []string{"sh", "check.sh"}
	writeGoLawModule(t, root, module)
	writeConfig(t, root, []inventory.Module{module})
	writeFreshnessFixture(t, root, ".")
	writeFixture(t, root, "check.sh", "printf 'lawgate-freshness\\tfresh\\tstates_gen.go\\n'\nexit 9\n")
	directory, err := runCheck(t, root)
	if err == nil {
		t.Fatal("check accepted a failing generate_check with fresh target evidence")
	}
	assertReport(t, directory, "001.xml", "generated-is-fresh command", "exit status 9")
}

// TestGenerationRejectsUncoveredGeneratedSource enforces generated-is-fresh
// for every Go file identified by its generated header.
func TestGenerationRejectsUncoveredGeneratedSource(t *testing.T) {
	t.Run("no generation command", checkModuleWithoutGenerationCommand)
	root := t.TempDir()
	module := fixtureModule(".", withoutMachines)
	module.GenerateCheck = []string{"sh", "check.sh"}
	writeGoLawModule(t, root, module)
	writeConfig(t, root, []inventory.Module{module})
	writeFreshnessFixture(t, root, ".")
	writeFixture(t, root, "other.go", generatedFixture)
	directory, err := runCheck(t, root)
	if err == nil {
		t.Fatal("check accepted an uncovered generated file")
	}
	assertReport(t, directory, "001.xml", "other.go", "no target covers")
}

func checkModuleWithoutGenerationCommand(t *testing.T) {
	root := t.TempDir()
	module := fixtureModule(".", withoutMachines)
	writeGoLawModule(t, root, module)
	writeConfig(t, root, []inventory.Module{module})
	if _, err := runCheck(t, root); err != nil {
		t.Fatalf("module without generated files should pass without generate_check: %v", err)
	}
	writeFixture(t, root, "states_gen.go", generatedFixture)
	directory, err := runCheck(t, root)
	if err == nil {
		t.Fatal("check accepted generated source without generate_check")
	}
	assertReport(t, directory, "001.xml", "module must declare generate_check for states_gen.go")
}

const generatedFixture = "// Code generated by fixture. DO NOT EDIT.\npackage fixture\n"

func writeFreshnessFixture(t *testing.T, root, module string) {
	t.Helper()
	writeFixture(t, root, module+"/check.sh", `#!/bin/sh
if [ ! -f states_gen.go ]; then status=missing
elif cmp -s states_gen.go expected.txt; then status=fresh
else status=stale
fi
printf 'lawgate-freshness\t%s\tstates_gen.go\n' "$status"
[ "$status" = fresh ]
`)
	writeFixture(t, root, module+"/expected.txt", generatedFixture)
	writeFixture(t, root, module+"/states_gen.go", generatedFixture)
}
