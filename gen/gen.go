// Package gen writes Go types for a machine's states (layer 3 of the proof
// gate). Each state becomes a type whose methods are exactly its declared
// edges, so worker code can only move along edges the machine has: a move
// that is not declared does not compile. Every method records the move on a
// run.Run, which checks continuity at run time.
//
// A pass can only begin through an Enter function, and those exist only for
// the entry state and the states marked PassEntry. Enter functions and edge
// methods return a typed state and an error. The run counts limited edge
// traversals within the pass. A target state that is not generated becomes
// a type with no methods, which ends the typed part of the pass.
package gen

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"go/token"
	"sort"

	"github.com/pantacor/lawgate/machine"
)

// Options says what to generate and where it lives.
type Options struct {
	Package   string   // Go package of the generated file
	Prefix    string   // starts every type name ("appliance" gives applianceConverge)
	Command   string   // the command that regenerates the file, for its header
	RunImport string   // import path of package run, e.g. "github.com/pantacor/lawgate/run"
	States    []string // the states to generate
}

func (o Options) check(m *machine.Machine) error {
	if o.Package == "" {
		return errors.New("gen: no Package")
	}
	if o.RunImport == "" {
		return errors.New("gen: no RunImport: the generated code must name the run package it records moves on")
	}
	if len(o.States) == 0 {
		return errors.New("gen: no States to generate")
	}
	for _, id := range o.States {
		if m.State(id) == nil {
			return fmt.Errorf("gen: state %q is not declared in machine %s", id, m.Name)
		}
	}
	return nil
}

// Go returns the formatted Go source for the states opts names.
func Go(m *machine.Machine, opts Options) ([]byte, error) {
	if err := opts.check(m); err != nil {
		return nil, err
	}
	outside := map[string]bool{}
	names := map[string]string{
		"run":   "the run package import",
		"error": "the predeclared error type",
		"nil":   "the predeclared nil value",
	}
	w := &writer{m: m, opts: opts, generated: setOf(opts.States), outside: outside, names: names}
	w.header()
	if err := w.states(); err != nil {
		return nil, err
	}
	if err := w.outsideTypes(); err != nil {
		return nil, err
	}
	out, err := format.Source(w.buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gen: formatting the generated code: %w", err)
	}
	return out, nil
}

type writer struct {
	m         *machine.Machine
	opts      Options
	buf       bytes.Buffer
	generated map[string]bool
	outside   map[string]bool   // targets that are not generated
	names     map[string]string // package declarations share one Go namespace
	starts    int               // Enter functions written
}

func (w *writer) printf(format string, args ...any) {
	fmt.Fprintf(&w.buf, format, args...)
}

func (w *writer) header() {
	w.printf("// Code generated by %s; DO NOT EDIT.\n\n", w.opts.Command)
	w.printf("package %s\n\nimport run %q\n\n", w.opts.Package, w.opts.RunImport)
}

func (w *writer) states() error {
	for _, id := range w.opts.States {
		if err := w.state(w.m.State(id)); err != nil {
			return err
		}
	}
	if w.starts == 0 {
		return fmt.Errorf("gen: none of the generated states of %s is the entry state or a pass entry, so no pass could start", w.m.Name)
	}
	return nil
}

func (w *writer) state(st *machine.State) error {
	typ := typeName(w.opts.Prefix, st.ID)
	if err := w.claimName(typ, fmt.Sprintf("type for state %q", st.ID)); err != nil {
		return err
	}
	w.printf("// %s is state %q of machine %s.\n", typ, st.ID, w.m.Name)
	if st.Doc != "" {
		w.printf("// %s\n", oneLine(st.Doc))
	}
	w.printf("type %s struct{ run *run.Run }\n\n", typ)
	if err := w.enterIfAllowed(st, typ); err != nil {
		return err
	}
	names := map[string]bool{}
	for _, edge := range st.Edges {
		if err := w.checkEdge(st.ID, edge, names); err != nil {
			return err
		}
		w.edge(st.ID, typ, edge)
	}
	return nil
}

func (w *writer) enterIfAllowed(st *machine.State, typ string) error {
	if st.ID != w.m.EntryID() && !st.PassEntry {
		return nil
	}
	name := enterName(typ)
	if err := w.claimName(name, fmt.Sprintf("entry function for state %q", st.ID)); err != nil {
		return err
	}
	w.starts++
	w.printf("// %s starts a pass in state %q.\n", name, st.ID)
	recorder := moveLocal("r", typ)
	w.printf("func %s(%s *run.Run) (%s, error) {\n", name, recorder, typ)
	w.checkedMove(typ, recorder, "%s.Enter(%q)", recorder, st.ID)
	return nil
}

func (w *writer) checkEdge(stateID string, edge machine.Edge, names map[string]bool) error {
	if edge.Name == "" {
		return fmt.Errorf("gen: state %q: edge %q to %q has no Name; every edge of a generated state needs one", stateID, edge.On, edge.To)
	}
	if !usableIdentifier(edge.Name) {
		return fmt.Errorf("gen: state %q: edge name %q is not a usable Go identifier", stateID, edge.Name)
	}
	if edge.Name == machine.EntryEdgeName {
		return fmt.Errorf("gen: state %q: edge name %q is reserved for the start of a pass", stateID, edge.Name)
	}
	if edge.Name == "run" {
		return fmt.Errorf("gen: state %q: edge method run conflicts with the generated run field", stateID)
	}
	if names[edge.Name] {
		return fmt.Errorf("gen: state %q: two edges are named %s", stateID, edge.Name)
	}
	names[edge.Name] = true
	if w.m.State(edge.To) == nil {
		return fmt.Errorf("gen: state %q: edge %s goes to undeclared state %q", stateID, edge.Name, edge.To)
	}
	return nil
}

func (w *writer) outsideTypes() error {
	ids := make([]string, 0, len(w.outside))
	for id := range w.outside {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	for _, id := range ids {
		typ := typeName(w.opts.Prefix, id)
		if err := w.claimName(typ, fmt.Sprintf("type for outside state %q", id)); err != nil {
			return err
		}
		w.printf("// %s is state %q of machine %s, outside the generated states: the typed part of the pass ends here.\n", typ, id, w.m.Name)
		w.printf("type %s struct{ run *run.Run }\n\n", typ)
	}
	return nil
}

func (w *writer) claimName(name, declaration string) error {
	if !usableIdentifier(name) {
		return fmt.Errorf("gen: %s produces %q, which is not a usable Go identifier", declaration, name)
	}
	if previous, exists := w.names[name]; exists {
		return fmt.Errorf("gen: Go name %q conflicts between %s and %s", name, previous, declaration)
	}
	w.names[name] = declaration
	return nil
}

func usableIdentifier(name string) bool {
	return name != "_" && token.IsIdentifier(name)
}

func setOf(ids []string) map[string]bool {
	set := make(map[string]bool, len(ids))
	for _, id := range ids {
		set[id] = true
	}
	return set
}
