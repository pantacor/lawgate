package gosource

import (
	"os"
	"path/filepath"
	"slices"
	"testing"
)

func TestSourcePathPolicy(t *testing.T) {
	tests := []struct {
		path      string
		skipped   bool
		sensitive bool
	}{
		{path: "secrets.go"},
		{path: "secrets/go.mod"},
		{path: ".env/secrets/worker.go", skipped: true},
		{path: "secrets/check.js"},
		{path: "secrets/private.key", sensitive: true},
		{path: "worker/.env.local", sensitive: true},
		{path: "testdata/secrets/worker.go", skipped: true},
		{path: "node_modules/dep/worker.go", skipped: true},
		{path: "_internal/worker.go", skipped: true},
		{path: "worker/normal.txt"},
	}
	for _, item := range tests {
		if Skipped(item.path) != item.skipped || Sensitive(item.path) != item.sensitive {
			t.Errorf("%s: skipped=%v, sensitive=%v", item.path, Skipped(item.path), Sensitive(item.path))
		}
	}
}

func TestWalkRefusesSymlinkedGoSource(t *testing.T) {
	root := t.TempDir()
	filename := filepath.Join(root, "machine.txt")
	if err := os.WriteFile(filename, []byte("package p"), 0600); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(filename, filepath.Join(root, "machine.go")); err != nil {
		t.Skipf("cannot create a symlink: %v", err)
	}
	if files, err := Files(root); err == nil || len(files) != 0 {
		t.Fatalf("files=%v, error=%v", files, err)
	}
}

func TestGeneratedFilesUseGoHeader(t *testing.T) {
	root := t.TempDir()
	files := map[string]string{
		"inactive_test.go": "//go:build absent\n\n// Code generated by tool. DO NOT EDIT.\npackage p\n",
		"body.go":          "package p\n// Code generated by tool. DO NOT EDIT.\n",
		"note.txt":         "// Code generated by tool. DO NOT EDIT.\n",
	}
	for name, content := range files {
		if err := os.WriteFile(filepath.Join(root, name), []byte(content), 0600); err != nil {
			t.Fatal(err)
		}
	}
	got, err := GeneratedFiles(root)
	if err != nil || !slices.Equal(got, []string{"inactive_test.go"}) {
		t.Fatalf("generated files=%v, error=%v", got, err)
	}
}
